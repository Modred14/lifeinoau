async function request(path, cookie, body) {
  const response = await fetch(site + path, { method: body === undefined ? "GET" : "POST", headers: { origin: site, "content-type": "application/json", "x-forwarded-for": "198.51.100.77", ...(cookie ? { cookie } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const data = await response.json();
  return { status: response.status, data, cookie: response.headers.get("set-cookie")?.split(";")[0] };
}
async function waitFor(fn, label, ms = 10000) {
  const end = Date.now() + ms;
  while (Date.now() < end) { const out = await fn(); if (out) return out; await new Promise((r) => setTimeout(r, 50)); }
  throw new Error(`Timed out: ${label}`);
}
async function makePerson(tag) {
  const suffix = randomUUID().slice(0, 8), email = `campus_${tag}_${suffix}@example.invalid`.toLowerCase(), password = `Local-${randomUUID()}`;
  const signup = await request("/api/signup", null, { email, password, isAdult: true });
  assert.equal(signup.status, 200, JSON.stringify(signup.data));
  const cookie = signup.cookie;
  const meta = await request("/api/meta", cookie);
  const faculty = meta.data.faculties.find((f) => /Science/.test(f.name));
  const name = `Campus${tag}${suffix}`;
  const created = await request("/api/character", cookie, { name, gender: "M", facultyId: faculty.id, personalities: ["Shana"] });
  assert.equal(created.status, 200, JSON.stringify(created.data));
  const hostel = created.data.hostels.includes("Awo") ? "Awo" : created.data.hostels[0];
  const moved = await request("/api/character/hostel", cookie, { hostel });
  assert.equal(moved.status, 200, JSON.stringify(moved.data));
  const user = await db.user.findUniqueOrThrow({ where: { email }, include: { character: { include: { account: true } } } });
  const person = { email, password, cookie, user, name };
  people.push(person);
  return person;
}
