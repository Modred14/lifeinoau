import { makeDb } from "./db.mjs";
import { economyStats, transactions, suspicious } from "../../../lib/adminEconomy.js";
import { presenceList } from "../../../lib/adminPresence.js";
import { jsonSafe } from "../../../lib/adminCore.js";
const db = makeDb();
const e = jsonSafe(await economyStats(db));
console.log("players", e.players, "total", e.totalKobo, "max", e.maxKobo, "median", e.medianKobo);
console.log("dist", e.distribution.map((d) => `${d.label}:${d.players}`).join(" | "));
console.log("wealthy[0..2]", e.wealthy.slice(0, 3).map((w) => `${w.name} ${w.balance} x${w.timesMedian} unusual=${w.unusual}`));
console.log("movers", e.movers.length, "system", e.system.map((s) => s.name + "=" + s.balance).join(","));
const t = jsonSafe(await transactions(db, { kind: "players", page: 1 }));
console.log("tx total", t.total, "rows", t.rows.length);
const t2 = jsonSafe(await transactions(db, { q: "allowance", min: "1000000", sort: "amount", dir: "desc", pageSize: "3" }));
console.log("tx filtered", t2.total, t2.rows.map((r) => r.amountKobo));
const t3 = jsonSafe(await transactions(db, { player: "c0003" }));
console.log("tx player", t3.total, t3.rows[0]?.to);
const s = jsonSafe(await suspicious(db, {}));
console.log("suspicious", s.entries.length, s.entries[0]?.reasons, "threshold", s.thresholdKobo);
const p = jsonSafe(await presenceList(db, { live: new Set(["c0010"]) }));
console.log("presence", p.counts, p.players.map((x) => `${x.name}:${x.presence}[${x.sources}]`).join(", "));
await db.end();
