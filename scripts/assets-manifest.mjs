// scripts/assets-manifest.mjs
// Builds the asset manifest: every managed file (see assets.config.mjs) with a content hash, its size and its tier.
//
//   node scripts/assets-manifest.mjs            write the manifest (runs automatically before `dev` and `build`)
//   node scripts/assets-manifest.mjs --check    exit 1 if the committed manifest is out of date (runs in `npm test`)
//
// Two files come out, from the same data:
//   lib3d/assets/manifest.generated.js   imported by the game's code, so the code and the asset versions it asks for are ONE bundle: new code can never request an old version
//   public/asset-manifest.json           read by the service worker to throw away cached files that are no longer current (served with no-store, see next.config.mjs)
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { ASSET_ROOTS, TIER_RULES, DEFAULT_TIER, EXCLUDE } from "../assets.config.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUT_JS = path.join(ROOT, "lib3d/assets/manifest.generated.js");
export const OUT_JSON = path.join(ROOT, "public/asset-manifest.json");

const sha = (buf, n) => createHash("sha256").update(buf).digest("hex").slice(0, n);
const tierOf = (p) => TIER_RULES.find((r) => r.match.test(p))?.tier ?? DEFAULT_TIER;

function* walk(dir, rel = "") {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    const abs = path.join(dir, name), r = `${rel}/${name}`;
    if (statSync(abs).isDirectory()) yield* walk(abs, r);
    else yield [r, abs];
  }
}

/** The manifest for a public/ folder: { version, assets: { "/models/x.glb": { v, bytes, tier } } }. `version` changes when any managed file does. Pure apart from reading files. */
export function buildManifest(publicDir = path.join(ROOT, "public")) {
  const assets = {};
  for (const root of ASSET_ROOTS) {
    for (const [rel, abs] of walk(path.join(publicDir, root), `/${root}`)) {
      if (EXCLUDE.some((re) => re.test(rel))) continue;
      const buf = readFileSync(abs);
      assets[rel] = { v: sha(buf, 10), bytes: buf.length, tier: tierOf(rel) };
    }
  }
  const sorted = Object.fromEntries(Object.entries(assets).sort(([a], [b]) => (a < b ? -1 : 1)));
  const version = sha(Buffer.from(Object.entries(sorted).map(([p, a]) => `${p}:${a.v}`).join("\n")), 12);
  return { version, assets: sorted };
}

export const renderJs = (m) => `// lib3d/assets/manifest.generated.js\n// GENERATED by scripts/assets-manifest.mjs from public/ (see assets.config.mjs). Do not edit by hand: run \`npm run assets:build\`.\nexport default ${JSON.stringify(m, null, 1)};\n`;
export const renderJson = (m) => JSON.stringify(m) + "\n";

export function writeManifest(m = buildManifest()) {
  writeFileSync(OUT_JS, renderJs(m)); writeFileSync(OUT_JSON, renderJson(m)); return m;
}

/** What is wrong with the committed manifest files compared with the files on disk (empty = fine). */
export function manifestProblems(m = buildManifest()) {
  const out = [];
  const same = (file, want) => { try { return readFileSync(file, "utf8") === want; } catch { return false; } };
  if (!same(OUT_JS, renderJs(m))) out.push("lib3d/assets/manifest.generated.js is out of date");
  if (!same(OUT_JSON, renderJson(m))) out.push("public/asset-manifest.json is out of date");
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  if (process.argv.includes("--check")) {
    const problems = manifestProblems();
    if (problems.length) { console.error(problems.join("\n") + "\nRun: npm run assets:build"); process.exit(1); }
    console.log("asset manifest is up to date");
  } else {
    const m = writeManifest(), n = Object.keys(m.assets).length, mb = Object.values(m.assets).reduce((s, a) => s + a.bytes, 0) / 1048576;
    console.log(`asset manifest: ${n} files, ${mb.toFixed(1)} MB, version ${m.version}`);
  }
}
